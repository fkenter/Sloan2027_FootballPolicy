def nm(t):
    return DISPLAY.get(TEAMS_SIM[t] if isinstance(t, (int, np.integer)) else t, TEAMS_SIM[t] if isinstance(t, (int, np.integer)) else t)


def outcome_stats(k):
    """Plain statistics of what a policy produces, from replication 0 of the main experiment."""
    R = MAIN[(MAIN.policy == k) & (MAIN.rep == 0)].sort_values("season")
    G = np.array(R.groups.tolist())
    out = {}
    if k in ("fbs_tiers", "conf_tiers"):
        moved = (G[1:] != G[:-1]).mean(1)
        out["teams changing tier per season"] = f"{moved.mean() * CTX.N:.0f} of {CTX.N}"
    if k == "fbs_tiers":
        top = G == G.min(1, keepdims=True)
        out["different programs reaching the top tier over the 50 seasons"] = int(top.any(0).sum())
        runs = []
        for t in range(CTX.N):
            r = 0
            for v in top[:, t]:
                if v:
                    r += 1
                elif r:
                    runs.append(r); r = 0
            if r:
                runs.append(r)
        out["median consecutive seasons in the top tier"] = float(np.median(runs)) if runs else 0
        tv = [(s, i, j, med) for s, rows in enumerate(R.tv) for (i, j, med, *_rest) in rows]
        tiers_tv = np.array([min(G[s][i], G[s][j]) for s, i, j, _ in tv])
        bc = np.array([m == "broadcast" for *_x, m in tv])
        for lab, lo, hi in [("tier 1", 0, 0), ("tiers 2–3", 1, 2), ("tiers 4–6", 3, 5), ("tier 7 or lower", 6, 99)]:
            sel = (tiers_tv >= lo) & (tiers_tv <= hi)
            out[f"televised games whose better team is in {lab}"] = f"{100 * sel.mean():.0f}% (broadcast network: {100 * (sel & bc).sum() / bc.sum():.0f}%)"
    out["teams never televised in a season (mean)"] = f"{R.never_on_tv.mean():.0f}"
    return out


def fmt_pct(x):
    return f"{x:+.1f}%"


