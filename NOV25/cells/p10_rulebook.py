# --- (iv) FBS-wide tiers
if "fbs_tiers" in best:
    b = best["fbs_tiers"]
    T = max(1, int(round(CTX.N / b["n"])))
    sizes = [len(x) for x in np.array_split(np.arange(CTX.N), T)]
    size_txt = ", ".join(f"{sizes.count(v)} tiers of {v}" for v in sorted(set(sizes), reverse=True))
    tier_games = f"{min(sizes) - 1}–{max(sizes) - 1}" if len(set(sizes)) > 1 else f"{sizes[0] - 1}"
    other = f"{SEASON_GAMES - (max(sizes) - 1)}–{SEASON_GAMES - (min(sizes) - 1)}" if len(set(sizes)) > 1 else f"{SEASON_GAMES - (sizes[0] - 1)}"
    fill_txt = ("against the teams closest to it in the league table that are not in its own tier (in practice, the "
                "bottom of the tier above and the top of the tier below)" if b["fill"] == "adjacent"
                else "against teams drawn at random from the tier directly above and the tier directly below")
    move_txt = (f"The top **{b['p']}** teams of each tier are promoted and the bottom **{b['p']}** are relegated (the top "
                "tier only relegates, the bottom tier only promotes)." if b["p"] != "re-sort" else
                "All teams are re-sorted by the results-based rating and cut into tiers again (no fixed number moves).")
    r = TWO_BY_TWO.set_index("policy").loc[NAMES["fbs_tiers"]]
    lines += ["## FBS-wide tiers (promotion and relegation across FBS)", "", "**The rules**", "",
              f"1. **Tiers.** All {CTX.N} FBS teams are ranked and cut into {T} tiers ({size_txt}).",
              f"2. **Schedule.** Each team plays everyone in its tier once ({tier_games} games) and its remaining "
              f"{other} games {fill_txt}.",
              "3. **Standings.** Within each tier, by wins; ties broken by point differential.",
              f"4. **Promotion and relegation.** {move_txt}",
              "5. **Television.** Networks choose the 303 national windows from the published schedule to maximize "
              "predicted viewers, under the same window limits as today.", "",
              "**What it produces (simulation)**", "",
              f"* Season viewers: **{r['policy, optimized TV']:,.0f}M** with optimized TV ({fmt_pct(r['policy effect, optimized TV %'])} "
              f"vs the status quo with optimized TV) and {r['policy, 2019-style TV']:,.0f}M if networks keep their 2019 habits "
              f"({fmt_pct(r['policy effect, 2019-style TV %'])} vs the status quo with 2019-style TV).",
              f"* Against the 2019 televised games by rank: {fmt_pct(r['both vs 2019 slate by rank (A) %'])}.",
              f"* Beats the status quo (both optimized) in {r['policy wins seasons % (opt TV)']:.0f}% of seasons."]
    lines += [f"* {kk[0].upper() + kk[1:]}: {v}." for kk, v in outcome_stats("fbs_tiers").items()]
