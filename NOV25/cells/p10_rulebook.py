    ex = R.iloc[min(10, len(R) - 1)]
    G = np.array(ex.groups)
    lines += ["", f"*Example: season {int(ex.season) + 1} of one simulated future.*", ""]
    for t in range(3):
        lines.append(f"* Tier {t + 1}: " + ", ".join(nm(i) for i in np.nonzero(G == t)[0]))
    top = sorted(ex.tv, key=lambda x: -x[5])[:5]
    lines += ["* Most-watched games: " + "; ".join(f"{nm(i)} v {nm(j)} (week {w}, {tm}, {md}, {v:.1f}M)" for i, j, md, tm, w, v in top), ""]

